  function setLang(lang) {
    if (STR[lang]) current = lang;
    if (typeof document !== 'undefined') {
      document.documentElement.setAttribute('lang', current);
    }
    return current;
  }
  function getLang() { return current; }
  function langs() { return Object.keys(STR); }

  function t(key, params) {
    const dict = STR[current] || STR.uz;
    let s = dict[key];
    if (s == null) s = STR.uz[key];
    if (s == null) s = key;
    if (params) {
      for (const k in params) s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), params[k]);
    }
    return s;
  }

  LV.i18n = { t, setLang, getLang, langs, STR };
